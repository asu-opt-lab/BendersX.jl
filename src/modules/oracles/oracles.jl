# Common interface 
# ----------------------------------------------------------------------------
"""
    generate_cuts(
        oracle::AbstractOracle,
        x_value::Vector{Float64},
        t_value::Vector{Float64};
        tol_normalize = 1.0,
        time_limit = 3600,
    )

Generate cuts for a candidate master solution.

Concrete [`AbstractOracle`](@ref) types implement this method to evaluate the candidate point and, when necessary, generate valid inequalities separating it from the oracle's associated feasible region, denoted by `L`. For typical oracles, `L` is the set defined by all Benders cuts; for disjunctive oracles, `L` is the corresponding disjunctive set.

# Arguments

- `oracle::AbstractOracle`: Oracle used to evaluate and separate the candidate solution.
- `x_value`: Candidate values of the master variables `x`.
- `t_value`: Candidate values of the auxiliary variables `t`.
- `tol_normalize`: Normalization factor used during cut generation (default: 1.0). This parameter is used internally by disjunctive oracles and typically does not need to be specified by users.
- `time_limit`: Maximum time allowed for the oracle evaluation, in seconds.

# Returns

A tuple `(is_in_L, hyperplanes, sub_obj_vals)` where:

- `is_in_L::Bool`: Whether the candidate point belongs to `L`.
- `hyperplanes::Vector{Hyperplane}`: Valid inequalities generated by the oracle.
- `sub_obj_vals::Vector{Float64}`: Subproblem objective values used for updating the master upper bound. Values may be `Inf` when no meaningful objective is available.

This fallback method is called only when no implementation is available for the concrete oracle type.
"""
function generate_cuts(oracle::AbstractOracle, x_value::Vector{Float64}, t_value::Vector{Float64}; tol_normalize = 1.0, time_limit = 3600)
    throw(UnimplementedInterfaceException("update generate_cuts for $(typeof(oracle))"))
end

